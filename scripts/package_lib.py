"""Shared rules for building and verifying the portable package. Pure standard library, runs on every OS."""
from __future__ import annotations

import fnmatch
import hashlib
import re
from pathlib import Path

# Only these top-level paths can ever enter the package (intersected with git-tracked files).
ALLOW = (
    "CLAUDE.md", "AGENTS.md", "README.md", "README.ar.md", "LICENSE", "THIRD_PARTY_NOTICES.md",
    "CONTRIBUTING.md", "SECURITY.md", "CHANGELOG.md", "package.json", "package-lock.json", "requirements-media.txt", "tsconfig.json",
    "tsconfig.production.json", "remotion.config.ts", ".gitignore", ".gitattributes", "run-studio.sh", "render-audio.sh",
    "render-sample.sh", "healthcheck.sh", "blender-studio.sh", "run-studio.ps1", "run-studio.cmd",
    "src/", "tests/", "scripts/", "config/", "docs/", "schemas/", ".github/",
    "third_party/", ".agents/", ".claude/commands/", "public/fonts/", "public/sfx/", "public/audio-projects/audio-motion-sample/",
    "public/audio-projects/.gitkeep", "production/style-profiles/", "production/examples/", "production/reports/", "fixtures/cybersecurity-voice.wav",
)

DENY_GLOBS = (
    "*.mp4", "*.mov", "*.mkv", "*.m4a", "*.mp3", "*.aac", "*.flac", "*.ogg", "*.avi", "*.webm", "*.bin", "*.gguf", "*.onnx", "*.pt",
    ".env", ".env.*", "*.pem", "*.key", "*.p12", "*.pfx", "id_rsa*", "*.keystore", "haska.config.json", "settings.local.json",
    "*credentials*", "*secret*", "*token*", "auth.json", ".netrc", "*.log", "*.blend", "*.blend1",
)
DENY_DIRS = ("node_modules", ".cache", "out", "tools", "downloads", ".git", "__pycache__", "renders")
# The one wav we ship is the synthetic test voice generated by ffmpeg (documented in the audio sample).
DENY_EXCEPT = ("fixtures/cybersecurity-voice.wav",)
DENY_WAV = "*.wav"

SECRET_PATTERNS = [
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    re.compile(r"\bsk-[A-Za-z0-9]{20,}"),
    re.compile(r"\bghp_[A-Za-z0-9]{30,}"),
    re.compile(r"\bgithub_pat_[A-Za-z0-9_]{40,}"),
    re.compile(r"\bglpat-[A-Za-z0-9_-]{20,}"),
    re.compile(r"\bxox[baprs]-[A-Za-z0-9-]{20,}"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"(?i)\b(api[_-]?key|secret|token|password)\b['\"]?\s*[:=]\s*['\"][A-Za-z0-9_\-]{16,}['\"]"),
    re.compile(r"(?i)\bFAL_KEY\s*=\s*\S{8,}"),
]
TEXT_SUFFIXES = {".md", ".json", ".ts", ".tsx", ".js", ".mjs", ".cjs", ".py", ".sh", ".ps1", ".txt", ".css", ".html", ".yml", ".yaml", ".toml", ".swift", ".example", ""}
HOME_PATH = re.compile(r"(/home/[a-z0-9_.-]+/|/Users/[A-Za-z0-9_.-]+/|C:\\Users\\[A-Za-z0-9_.-]+\\)")


def posix(path: str | Path) -> str:
    return str(path).replace("\\", "/")


def allowed(rel: str, include_personal: bool) -> bool:
    # Public packaging never includes personal project paths, even if an older caller passes True.
    return any(rel == p or (p.endswith("/") and rel.startswith(p)) for p in ALLOW)


def denied(rel: str) -> str | None:
    """Reason a path may never be packaged, or None."""
    parts = rel.split("/")
    name = parts[-1]
    if any(part in DENY_DIRS for part in parts[:-1]):
        return "excluded directory"
    if rel in DENY_EXCEPT:
        return None
    if fnmatch.fnmatch(name, DENY_WAV):
        return "audio recording"
    for pattern in DENY_GLOBS:
        if fnmatch.fnmatch(name.lower(), pattern):
            return f"matches {pattern}"
    return None


def scan_text(rel: str, data: bytes) -> list[str]:
    """Findings (never the secret itself) for credentials or machine-specific home paths in a text file."""
    if b"\0" in data[:2048]:
        return []
    text = data.decode("utf-8", errors="replace")
    findings = [f"{rel}: possible credential ({p.pattern[:28]}...)" for p in SECRET_PATTERNS if p.search(text)]
    return findings


def home_path_findings(rel: str, data: bytes, allow_in: tuple[str, ...] = ("docs/", "third_party/", "THIRD_PARTY_NOTICES.md", "tests/", "scripts/package_lib.py", "scripts/gen_parity_matrix.py")) -> list[str]:
    if rel.startswith(allow_in) or Path(rel).suffix.lower() not in TEXT_SUFFIXES or b"\0" in data[:2048]:
        return []
    hit = HOME_PATH.search(data.decode("utf-8", errors="replace"))
    return [f"{rel}: machine-specific path {hit.group(0)!r}"] if hit else []


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()
