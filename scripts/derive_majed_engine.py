#!/usr/bin/env python3
"""Derive src/majed/engine-core.js from the vendored upstream engine.js (MIT, Majed Alzaabi).

The upstream engine is a page-bound module (URL parameters, DOM lookups, fetch, WebGL). The 100 motion moves only need
its pure helpers: math/easing/noise, the Arabic text engine (word layout, kashida, joining), hand-drawn paths, and
beat/word timing. This script lifts exactly those blocks, byte for byte, between marker comments and wraps them in a factory,
so the result can be regenerated and diffed whenever the pinned upstream commit changes.

    python3 scripts/derive_majed_engine.py          # regenerate
    python3 scripts/derive_majed_engine.py --check  # fail if src/majed/engine-core.js is stale
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / "third_party" / "majed-video"
SOURCE = UPSTREAM / "motion" / "engine.js"
TARGET = ROOT / "src" / "majed" / "engine-core.js"

# (start marker, end marker) pairs; text between them is copied verbatim. End markers are exclusive.
BLOCKS = [
    ("/* ─────────────────────────── math · easing", "/* ─────────────────────────── state"),
    ("/* ─────────────────────────── Arabic text", "function textCanvas("),
    ("/* ─────────────────────────── hand-drawn strokes", "/* ─────────────────────────── transitions"),
]
EXPORTS = (
    "clamp, lerp, prog, map, smoothstep, fract, E, kf, cubicBezier, springFn, hashStr, rng, hash01, noise1, noise2, fbm, "
    "westernDigits, fontStr, applyFont, kashida, visualOrder, layout, drawLayout, text, drawKashida, fit, typeSub, "
    "pathInfo, drawPath, beatIndex, beatTime, beatPhase, beatPulse, barIndex, onBar, barPulse, nearestBeat, section, line, "
    "wordTime, lineSpan, wordsOf, activeWord"
)


def slice_between(source: str, start: str, end: str) -> str:
    a = source.find(start)
    if a < 0:
        raise SystemExit(f"start marker not found: {start!r}")
    a = source.rfind("\n", 0, a) + 1
    b = source.find(end, a + len(start))
    if b < 0:
        raise SystemExit(f"end marker not found: {end!r}")
    b = source.rfind("\n", 0, b) + 1 if end.startswith("/*") else b
    return source[a:b]


def build() -> str:
    manifest = json.loads((UPSTREAM / "UPSTREAM.json").read_text())
    recorded = next(f["sha256"] for f in manifest["files"] if f["path"].endswith("motion/engine.js"))
    actual = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    if recorded != actual:
        raise SystemExit("vendored engine.js does not match UPSTREAM.json; re-run scripts/vendor_majed.py")
    source = SOURCE.read_text(encoding="utf-8")
    body = "\n".join(slice_between(source, a, b) for a, b in BLOCKS)
    commit = manifest["upstream"]["commit"]
    return f"""/* GENERATED by scripts/derive_majed_engine.py: do not edit.
 *
 * Derived from motion/engine.js of https://github.com/majedphotos/video-ad-editor @ {commit}
 * (MIT License, Copyright (c) 2026 Majed Alzaabi; see third_party/majed-video/LICENSE).
 * Only the pure helper blocks are copied verbatim (math/easing/noise, Arabic text engine, hand-drawn paths, beat and
 * word timing). The page-bound parts (URL parameters, DOM, fetch, WebGL, scene runtime) are not included.
 * `createEngineCore(S)` receives the mutable state the blocks read: {{P, fps, spb, bpb, bpm, beats, bars, tl, vo, voList}}.
 */
export function createEngineCore(S) {{
{body}
  const setFamilies = (map) => {{ FAMS = Object.assign(FAMS, map); }};
  return {{ {EXPORTS}, setFamilies, get FAMS() {{ return FAMS; }} }};
}}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = build()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != generated:
            print("src/majed/engine-core.js is stale; run: python3 scripts/derive_majed_engine.py")
            return 1
        print("engine-core.js is up to date")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(generated, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(generated.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
